/**
 * Shared types for document (DOCX) read-only preview.
 *
 * The parse result crosses a worker boundary and then an HTTP boundary, so everything here
 * is plain JSON — no Blobs, no Buffers, no functions. Image bytes deliberately stay on the
 * server: the client addresses them through `/api/fs/document-asset`, which re-reads a single
 * ZIP entry per request.
 */

/** Format decided by CONTENT signature first, extension only as a last hint. */
export type DocumentKind = "docx" | "legacy-office" | "pdf" | "unsupported";

/** One embedded picture, addressable through the asset endpoint. */
export interface DocumentAssetRef {
	/** Generated by the parser (`a1`, `a2`, …); never a client-supplied ZIP path. */
	id: string;
	/** MIME type inferred from the stored part's bytes/extension. */
	mime: string;
	/** Size of the extracted bytes, for the client's own budgeting. */
	byteLength: number;
}

export interface DocumentPreviewResult {
	kind: "docx";
	/** Markdown rendering of the document body, inline images as `nf-doc-asset:` links. */
	markdown: string;
	assets: DocumentAssetRef[];
	/** Set when the block/text budget cut the document short. */
	truncated: boolean;
	/** Non-fatal notes (unsupported constructs, budget hits) for the client to show. */
	omitted: string[];
	meta: { title?: string; author?: string };
}

export interface DocumentPreviewFailure {
	kind: "legacy-office" | "pdf" | "unsupported";
	/** i18n-independent reason; the client maps it to a localized message. */
	reason: string;
	/** Detail suitable for a log line, not for the person. */
	detail: string;
}

export type DocumentParseOutcome =
	| { ok: true; result: DocumentPreviewResult }
	| { ok: false; failure: DocumentPreviewFailure };

/** Prefix of the inline-image placeholder written into the Markdown body. */
export { DOCUMENT_ASSET_SCHEME } from "@shared/document-file-extensions";
