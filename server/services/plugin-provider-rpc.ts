/**
 * Narrow transport boundary used by the provider client. PluginRuntime satisfies
 * request/notify; notification and crash subscriptions are injected so tests and
 * future runtime wiring do not need to reimplement Content-Length framing.
 */
export interface ProviderRpcTransport {
	request<T = unknown>(
		method: string,
		params?: unknown,
		options?: ProviderRpcRequestOptions,
	): Promise<T>;
	notify(method: string, params?: unknown): Promise<void>;
	onNotification?(
		handler: (notification: JsonRpcNotification, bodyBytes?: number) => void,
	): () => void;
	onClose?(handler: (error?: Error) => void): () => void;
	kill?(reason: string): void | Promise<void>;
}

export interface PluginRuntimeProviderTransportOptions {
	subscribeNotifications?: (
		handler: (notification: JsonRpcNotification, bodyBytes?: number) => void,
	) => () => void;
	subscribeClose?: (handler: (error?: Error) => void) => () => void;
	kill?: (reason: string) => void | Promise<void>;
}

/** Adapts PluginRuntime without replacing its request registry or stdio framing. */
export class PluginRuntimeProviderTransport implements ProviderRpcTransport {
	constructor(
		private readonly runtime: Pick<PluginRuntime, "request" | "notify" | "quarantine">,
		private readonly options: PluginRuntimeProviderTransportOptions = {},
	) {}

	request<T = unknown>(
		method: string,
		params?: unknown,
		options: ProviderRpcRequestOptions = {},
	): Promise<T> {
		return this.runtime.request<T>(method, params, {
			signal: options.signal,
			timeoutMs: options.timeoutMs,
		});
	}

	notify(method: string, params?: unknown): Promise<void> {
		return this.runtime.notify(method, params);
	}

	onNotification(
		handler: (notification: JsonRpcNotification, bodyBytes?: number) => void,
	): () => void {
		return this.options.subscribeNotifications?.(handler) ?? (() => undefined);
	}

	onClose(handler: (error?: Error) => void): () => void {
		return this.options.subscribeClose?.(handler) ?? (() => undefined);
	}

	kill(reason: string): void | Promise<void> {
		if (this.options.kill) return this.options.kill(reason);
		this.runtime.quarantine(reason);
	}
}

