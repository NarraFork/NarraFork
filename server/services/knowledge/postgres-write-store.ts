async function writeSpecFileRevisionSection(
	tx: PgTransaction,
	input: WriteSpecFileRevisionWrite,
): Promise<SpecFileWriteResult> {
	const current = await tx
		.select()
		.from(specNamespaceFiles)
		.where(
			and(
				eq(specNamespaceFiles.namespaceId, input.namespaceId),
				eq(specNamespaceFiles.path, input.path),
			),
		)
		.limit(1);

	let locks: SpecProtectedLockRow[] = [];
	if (input.specTasks) {
		locks = await tx
			.select({
				id: specProtectedTasks.id,
				textHash: specProtectedTasks.textHash,
				text: specProtectedTasks.text,
				status: specProtectedTasks.status,
				completedAt: specProtectedTasks.completedAt,
			})
			.from(specProtectedTasks)
			.where(eq(specProtectedTasks.namespaceId, input.namespaceId));
		const protectedMutations = input.specTasks.detectProtectedMutations(locks);
		if (protectedMutations.length > 0 && !input.specTasks.allowProtectedTaskMutation) {
			// Nothing has been written yet; returning the verdict is a clean no-op, and
			// withPgRetry does not replay a non-error result.
			return { ok: false as const, protectedMutations };
		}
	}

	await tx.insert(specFileRevisions).values({
		id: input.revisionId,
		namespaceId: input.namespaceId,
		path: input.path,
		content: input.content,
		contentHash: input.contentHash,
		parentRevisionId: current[0]?.revisionId ?? null,
		sourceToolUseId: input.sourceToolUseId,
		sourceMessageId: input.sourceMessageId,
		createdBy: input.createdBy,
		createdAt: input.now,
	});

	if (current[0]) {
		await tx
			.update(specNamespaceFiles)
			.set({ revisionId: input.revisionId, deleted: false, updatedAt: input.now })
			.where(eq(specNamespaceFiles.id, current[0].id));
	} else {
		await tx.insert(specNamespaceFiles).values({
			id: input.fileIdForCreate,
			namespaceId: input.namespaceId,
			path: input.path,
			revisionId: input.revisionId,
			deleted: false,
			updatedAt: input.now,
		});
	}

	await tx
		.update(specNamespaces)
		.set({ updatedAt: input.now })
		.where(eq(specNamespaces.id, input.namespaceId));

	if (input.specTasks) {
		const existingByHash = new Map(locks.map((lock) => [lock.textHash, lock]));
		const protectedTasksInDoc = input.specTasks.tasks.filter((task) => task.protected);
		for (const task of protectedTasksInDoc) {
			const existing = existingByHash.get(task.textHash);
			if (!existing) {
				await tx.insert(specProtectedTasks).values({
					id: generateId(),
					namespaceId: input.namespaceId,
					textHash: task.textHash,
					text: task.text,
					status: task.status,
					firstRevisionId: input.revisionId,
					lastRevisionId: input.revisionId,
					createdAt: input.now,
					updatedAt: input.now,
					completedAt: task.status === "done" ? input.now : null,
				});
				continue;
			}
			await tx
				.update(specProtectedTasks)
				.set({
					status: task.status,
					lastRevisionId: input.revisionId,
					updatedAt: input.now,
					...(task.status === "done" && !existing.completedAt ? { completedAt: input.now } : {}),
				})
				.where(eq(specProtectedTasks.id, existing.id));
		}
		const hashesInDoc = protectedTasksInDoc.map((task) => task.textHash);
		for (const lock of locks) {
			if (lock.status !== "todo" && lock.status !== "doing" && lock.status !== "blocked") {
				continue;
			}
			if (hashesInDoc.includes(lock.textHash)) continue;
			await tx
				.update(specProtectedTasks)
				.set({
					status: "deleted",
					deletedAt: input.now,
					updatedAt: input.now,
					lastRevisionId: input.revisionId,
				})
				.where(eq(specProtectedTasks.id, lock.id));
		}
	}
	return { ok: true as const };
}

async function forkSpecNamespaceSection(
	tx: PgTransaction,
	input: ForkSpecNamespaceWrite,
): Promise<{ created: boolean }> {
	const existingChild = await tx
		.select({ id: specNamespaces.id })
		.from(specNamespaces)
		.where(eq(specNamespaces.narratorId, input.childNarratorId))
		.limit(1);
	if (existingChild[0]) return { created: false as const };
	await tx.insert(specNamespaces).values({
		id: input.childNamespaceId,
		narratorId: input.childNarratorId,
		forkedFromNamespaceId: input.parentNamespaceId,
		createdAt: input.now,
		updatedAt: input.now,
	});
	const parentFiles = await tx
		.select()
		.from(specNamespaceFiles)
		.where(
			and(
				eq(specNamespaceFiles.namespaceId, input.parentNamespaceId),
				eq(specNamespaceFiles.deleted, false),
			),
		);
	for (const file of parentFiles) {
		await tx.insert(specNamespaceFiles).values({
			id: generateId(),
			namespaceId: input.childNamespaceId,
			path: file.path,
			revisionId: file.revisionId,
			deleted: false,
			updatedAt: input.now,
		});
	}
	const parentProtectedTasks = await tx
		.select()
		.from(specProtectedTasks)
		.where(eq(specProtectedTasks.namespaceId, input.parentNamespaceId));
	for (const task of parentProtectedTasks) {
		await tx.insert(specProtectedTasks).values({
			id: generateId(),
			namespaceId: input.childNamespaceId,
			textHash: task.textHash,
			text: task.text,
			status: task.status,
			firstRevisionId: task.firstRevisionId,
			lastRevisionId: task.lastRevisionId,
			createdAt: input.now,
			updatedAt: input.now,
			completedAt: task.completedAt,
			deletedAt: task.deletedAt,
		});
	}
	return { created: true as const };
}

async function resetSpecNamespaceSection(
	tx: PgTransaction,
	input: { namespaceId: string; now: string },
): Promise<void> {
	await tx.delete(specNamespaceFiles).where(eq(specNamespaceFiles.namespaceId, input.namespaceId));
	await tx
		.update(specProtectedTasks)
		.set({ status: "deleted", deletedAt: input.now, updatedAt: input.now })
		.where(
			and(
				eq(specProtectedTasks.namespaceId, input.namespaceId),
				inArray(specProtectedTasks.status, ["todo", "doing", "blocked"]),
			),
		);
	await tx
		.update(specNamespaces)
		.set({ updatedAt: input.now })
		.where(eq(specNamespaces.id, input.namespaceId));
}

