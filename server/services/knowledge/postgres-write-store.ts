/** Transaction handle as produced by `db.transaction(async (tx) => …)`. PG-side only. */
type PgTransaction = Parameters<Parameters<BunSQLDatabase["transaction"]>[0]>[0];

/** The whole grant-delete section, named so the transaction call site stays a
 *  non-async arrow (see the header). */
async function deleteAclGrantSection(
	tx: PgTransaction,
	input: {
		grantId: string;
		writeSibling: {
			scopeType: string;
			scopeId: string | null;
			principalType: string;
			principalId: string;
		} | null;
	},
): Promise<void> {
	await tx.delete(aclGrants).where(eq(aclGrants.id, input.grantId));
	const sibling = input.writeSibling;
	if (sibling) {
		// The credential row and its write-capability sibling represented ONE grant in
		// the knowledge vocabulary; leaving the sibling behind would keep the authority
		// the caller just revoked.
		await tx
			.delete(aclGrants)
			.where(
				and(
					eq(aclGrants.scopeType, sibling.scopeType),
					sibling.scopeId === null
						? isNull(aclGrants.scopeId)
						: eq(aclGrants.scopeId, sibling.scopeId),
					eq(aclGrants.principalType, sibling.principalType),
					eq(aclGrants.principalId, sibling.principalId),
					eq(aclGrants.capability, "write"),
					isNull(aclGrants.domainKind),
				),
			);
	}
}

/** How deep `cause` chains are followed when looking for the driver error's detail. */
const MAX_CAUSE_DEPTH = 8;

/**
 * The constraint name the server attached to a unique violation, when it reported one.
 * Bun SQL surfaces it as `PostgresError.constraint`; Drizzle may wrap the driver error
 * under `cause`, so the chain is walked with the same bound `pg-errors.ts` uses.
 */
function extractConstraintName(error: unknown): string | null {
	let current: unknown = error;
	for (let depth = 0; depth < MAX_CAUSE_DEPTH; depth++) {
		if (!current || typeof current !== "object") return null;
		const constraint = (current as Record<string, unknown>).constraint;
		if (typeof constraint === "string" && constraint.length > 0) return constraint;
		current = (current as Record<string, unknown>).cause;
	}
	return null;
}

/**
 * Translate a unique violation into port vocabulary; everything else passes through.
 * The original error rides as `cause`, which keeps the SQLSTATE reachable for
 * classification — `withPgRetry` sees a unique-violation, not a retryable failure.
 */
function rethrowAsPortError(error: unknown): never {
	if (isPgUniqueViolation(error)) {
		throw new WriteConflictError("write conflicts with an existing row", {
			constraint: extractConstraintName(error),
			cause: error,
		});
	}
	throw error;
}

/** Translate conflicts for every write, including UPDATE races, after the whole
 * retry unit has rolled back. Never retry one statement inside a failed transaction. */
async function retryKnowledgeWrite<T>(
	run: () => Promise<T>,
	options: Parameters<typeof withPgRetry>[1],
): Promise<T> {
	try {
		return await withPgRetry(run, options);
	} catch (error) {
		if (error instanceof WriteConflictError) throw error;
		rethrowAsPortError(error);
	}
}

