async function createSubmissionSection(
	tx: PgTransaction,
	input: CreateSubmissionWrite,
): Promise<KnowledgeSubmissionRow> {
	// The draft row lock serializes submit-vs-edit: an updateDraftContent that
	// supersedes the open request can never interleave with this guard's
	// "no open request" read.
	await lockDraft(tx, input.draftId);
	const open = await tx
		.select({ id: knowledgeSubmissions.id, status: knowledgeSubmissions.status })
		.from(knowledgeSubmissions)
		.where(
			and(
				eq(knowledgeSubmissions.draftId, input.draftId),
				inArray(knowledgeSubmissions.status, [...CLAIMABLE_SUBMISSION_STATUSES]),
			),
		)
		.limit(1);
	if (open[0]) {
		throw new ValidationError(
			open[0].status === "conflict"
				? `This personal entry has a publish request in conflict (${open[0].id}). ` +
						"Withdraw it and publish again, or ask a reviewer to resolve the conflict."
				: `This personal entry already has a publish request awaiting review (${open[0].id}). ` +
						"Withdraw it first if you want to replace it.",
		);
	}
	const [submission] = await tx
		.insert(knowledgeSubmissions)
		.values({
			id: input.submissionId,
			draftId: input.draftId,
			entryId: input.entryId,
			collectionId: input.collectionId,
			title: input.title,
			submitterUserId: input.submitterUserId,
			baseRevisionId: input.baseRevisionId,
			proposedContent: input.proposedContent,
			keywordsJson: input.keywordsJson,
			changeNote: input.changeNote,
			previousSubmissionId: input.previousSubmissionId,
			round: input.round > 0 ? input.round : 1,
			status: "pending",
			createdAt: input.now,
		})
		.returning();
	if (!submission) throw new Error("submission insert returned no row");
	return submission;
}

