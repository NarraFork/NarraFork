/**
 * PostgreSQL implementation of `KnowledgeWriteStore`.
 *
 * Same capability as `sqlite-write-store.ts`, different engine — and deliberately not
 * the same code: what the two implementations share is the port (`write-store.ts`),
 * the section CONTENT (same reads, guards and writes in the same order) and the
 * domain errors. Everything dialect-shaped lives here: the PG schema, genuinely async
 * transactions, whole-section retry, row locks and conflict translation.
 *
 * HOW EACH REQUIREMENT OF THE PORT IS MET
 * ---------------------------------------
 * - PROMISE boundary: every method is honestly async against a networked driver. An
 *   `await` between BEGIN and COMMIT is safe here, which is exactly what the
 *   write-port base contrasts with the SQLite implementation's strictly synchronous
 *   section.
 * - ATOMICITY: each operation's whole section runs in one `db.transaction`. Any
 *   rejection rolls all of it back. Every section is a NAMED async function invoked
 *   through a non-async arrow (`db.transaction((tx) => section(tx, input))`) — the
 *   shape the transaction-atomicity gate requires, so no `async` callback literal
 *   ever reaches a `.transaction(` call site.
 * - RETRY: `withPgRetry` wraps the WHOLE section (BEGIN through COMMIT), never a
 *   single statement. Sections are idempotent under whole-section replay: every row
 *   id is pre-generated by the caller, so a replay after a commit whose
 *   acknowledgement was lost surfaces as a conflict (or a get-or-create hit) instead
 *   of duplicating anything.
 * - CONFLICTS AS VOCABULARY: SQLSTATE 23505 is translated to `WriteConflictError`
 *   (with the constraint name the server reported) before it can cross the port
 *   boundary. `withPgRetry` classifies that as a unique-violation and never retries
 *   it into a false success.
 *
 * SERIALIZATION POINTS (where SQLite's single writer was the lock)
 * ----------------------------------------------------------------
 * Under SQLite every section below serialized on the single-writer transaction.
 * PostgreSQL runs sections concurrently, so each guard takes the row lock that makes
 * its check-then-write atomic — the "row-lock form" of the claims
 * `revision-version.ts` freezes:
 *
 *   appendRevision / commitMergedRevision  lock the ENTRY row (`FOR UPDATE`) before
 *                                          reading MAX(version): two allocators can
 *                                          never observe the same maximum.
 *   getOrCreateActiveDraft                 locks the ENTRY row before the active-draft
 *                                          re-check (no unique index covers
 *                                          (entry, author, status), so the lock is
 *                                          what keeps two creators from both passing).
 *   createSubmissionGuarded / updateDraftContent / rebaseDraftContent /
 *   archivePersonalEntry                   lock the DRAFT row: a submit and an edit
 *                                          serialize, so "no open submission" and
 *                                          "supersede the open submission" can never
 *                                          interleave into two pending requests.
 *   markSubmissionConflict / commitMergedRevision / approveStandalonePublish /
 *   withdrawSubmissionGuarded / setSubmissionReviewVerdict
 *                                          lock the SUBMISSION row before the status
 *                                          re-check: two reviewers serialize, and the
 *                                          loser re-reads the winner's verdict.
 *
 * Lock order is always submission → entry and never the reverse, so concurrent
 * approve + direct-append cannot deadlock.
 */
