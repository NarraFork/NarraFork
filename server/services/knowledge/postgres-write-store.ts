/** Take the entry row lock (`FOR UPDATE`): the serialization point for version
 *  allocation and get-or-create-draft. No row means the entry does not exist; the
 *  subsequent FK then fails loudly, exactly like the counter claim would. */
async function lockEntry(tx: PgTransaction, entryId: string): Promise<void> {
	await tx
		.select({ id: knowledgeEntries.id })
		.from(knowledgeEntries)
		.where(eq(knowledgeEntries.id, entryId))
		.for("update")
		.limit(1);
}

/** Take the draft row lock: the serialization point for submit-vs-edit races. */
async function lockDraft(tx: PgTransaction, draftId: string): Promise<void> {
	await tx
		.select({ id: knowledgeDrafts.id })
		.from(knowledgeDrafts)
		.where(eq(knowledgeDrafts.id, draftId))
		.for("update")
		.limit(1);
}

/** Take the submission row lock: the serialization point for concurrent reviewers. */
async function lockSubmission(tx: PgTransaction, submissionId: string): Promise<void> {
	await tx
		.select({ id: knowledgeSubmissions.id })
		.from(knowledgeSubmissions)
		.where(eq(knowledgeSubmissions.id, submissionId))
		.for("update")
		.limit(1);
}

/**
 * Claim the next revision version for `entryId`. MUST be called with the entry row
 * lock already held (see {@link lockEntry}): the lock is what makes the MAX read and
 * the following insert atomic against concurrent allocators. This is the row-lock
 * form of the claim `revision-version.ts` freezes for the counter-column design.
 */
async function claimNextRevisionVersion(tx: PgTransaction, entryId: string): Promise<number> {
	const rows = await tx
		.select({ v: knowledgeRevisions.version })
		.from(knowledgeRevisions)
		.where(eq(knowledgeRevisions.entryId, entryId))
		.orderBy(desc(knowledgeRevisions.version))
		.limit(1);
	return (rows[0]?.v ?? KNOWLEDGE_REVISION_VERSION_BASE - 1) + 1;
}

/** PG twin of the SQLite helper: close the draft's open PENDING submissions. */
async function supersedeOpenSubmissions(
	tx: PgTransaction,
	draftId: string,
	now: string,
): Promise<InvalidatedSubmissionRef[]> {
	const stale = await tx
		.select({
			id: knowledgeSubmissions.id,
			submitterUserId: knowledgeSubmissions.submitterUserId,
		})
		.from(knowledgeSubmissions)
		.where(
			and(
				eq(knowledgeSubmissions.draftId, draftId),
				inArray(knowledgeSubmissions.status, [...SUPERSEDABLE_SUBMISSION_STATUSES]),
			),
		)
		.limit(OPEN_SUBMISSION_SCAN_LIMIT);
	if (stale.length === 0) return stale;
	await tx
		.update(knowledgeSubmissions)
		.set({ status: "superseded", reviewedAt: now })
		.where(
			and(
				eq(knowledgeSubmissions.draftId, draftId),
				inArray(knowledgeSubmissions.status, [...SUPERSEDABLE_SUBMISSION_STATUSES]),
			),
		);
	return stale;
}

