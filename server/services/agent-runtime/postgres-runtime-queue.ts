	async function enqueueSection(tx: PgRuntimeTx, input: MailboxInput): Promise<PgEnqueueResult> {
		const dedupeKey = mailboxDedupeKey(input);
		const existing = await tx
			.select()
			.from(mailbox)
			.where(and(eq(mailbox.narratorId, input.narratorId), eq(mailbox.dedupeKey, dedupeKey)));
		if (existing[0]) return { status: "duplicate", delivery: existing[0] };
		// Lost confirmations replay the original receipt even if the sender was subsequently
		// deleted; only a first acceptance must prove its referenced source exists here.
		if (input.kind === "agent_message") {
			const source = await tx
				.select({ id: narrators.id })
				.from(narrators)
				.where(eq(narrators.id, input.sourceNarratorId));
			if (!source[0]) throw new Error("Mailbox source narrator does not exist");
		}
		const sizes = validatePgInput(input);
		if (input.kind === "task_notice") {
			const earlier = await tx
				.select({ id: outbox.id })
				.from(outbox)
				.where(
					and(
						eq(outbox.recipientId, input.narratorId),
						eq(outbox.producerKind, input.noticeKind),
						eq(outbox.state, "pending"),
					),
				)
				.limit(1);
			if (earlier[0]) return { status: "publication_pending" };
		}
		if (
			!(await mailboxHasCapacityPg(
				tx,
				input.narratorId,
				input.kind,
				input.kind === "task_notice" ? input.noticeKind : undefined,
			))
		)
			return { status: "full" };
		if (!(await initializeLegacyMailboxPg(tx, input.narratorId)))
			throw new Error("Legacy mailbox requires another bounded initialization page");
		const arrivalSeq = await allocateArrivalSequencePg(tx, input.narratorId);
		const time = now();
		const inserted = await tx
			.insert(mailbox)
			.values({
				id: generateId(),
				narratorId: input.narratorId,
				text: input.text,
				kind: input.kind,
				noticeKind: input.kind === "task_notice" ? input.noticeKind : null,
				dedupeKey,
				deliveryId: generateId(),
				recipientMessageId:
					input.kind !== "user_input" ? (input.recipientMessageId ?? generateId()) : generateId(),
				sourceNarratorId: input.kind === "agent_message" ? input.sourceNarratorId : null,
				sourceToolCallId: input.kind === "agent_message" ? input.sourceToolCallId : null,
				sourceAttempt: input.kind === "agent_message" ? input.sourceAttempt : null,
				sourceKey: input.kind !== "user_input" ? input.sourceKey : input.requestKey,
				...sizes,
				projectedByteSize: input.projectedByteSize,
				arrivalSeq,
				seq: input.kind === "user_input" ? (input.seq ?? arrivalSeq) : arrivalSeq,
				priority: input.kind === "user_input" ? (input.priority ?? false) : false,
				createdBy: input.createdBy ?? null,
				...(input.kind === "user_input"
					? {
							imagesJson: input.imagesJson,
							creatorJson: input.creatorJson,
							textFilePathsJson: input.textFilePathsJson,
							fileReferencesJson: input.fileReferencesJson,
							commandText: input.commandText,
							bashCommand: input.bashCommand,
						}
					: {}),
				bufferedAt: time,
				updatedAt: time,
				dedupeExpiresAt:
					input.kind === "user_input"
						? new Date(Date.now() + L.userDedupeTtlMs).toISOString()
						: null,
			})
			.returning();
		const delivery = inserted[0];
		if (!delivery) throw new Error("Mailbox insert returned no row");
		return { status: "accepted", delivery };
	}

	async function enqueue(input: MailboxInput): Promise<PgEnqueueResult> {
		const label = "mailbox.enqueue";
		try {
			return await withPgRetry(() => db.transaction((tx) => enqueueSection(tx, input)), { label });
		} catch (error) {
			const translated = translateWriteError(error, label);
			// Idempotency under a lost acknowledgement: two first acceptances of the same
			// dedupe key race past the check-then-insert, the loser hits idx_nbm_dedupe
			// (23505), and "already exists" IS the outcome it wanted. The unique index is
			// the no-duplicate authority — the loser's row never exists.
			if (translated instanceof WriteConflictError) {
				const existing = await getByDedupe(input.narratorId, mailboxDedupeKey(input));
				if (existing) return { status: "duplicate", delivery: existing };
			}
			throw translated;
		}
	}

	// ── Producer admission sections (the P2 caller-migration consumption points) ──

	/**
	 * Agent-message admission: dedupe → execution receipt → enqueue in ONE section.
	 * A duplicate short-circuits BEFORE the receipt check (a replayed receipt may
	 * outlive its source tool-call row); a first acceptance must prove the exact
	 * persisted execution receipt — sender, attempt, tool-use id, identity version 1,
	 * no continuation origin — in the same transaction that inserts. There is no
	 * "read SQLite, then enqueue" split window on this path.
	 */
	async function admitAgentMessageSection(
		tx: PgRuntimeTx,
		input: MailboxInput & { kind: "agent_message" },
		receipt: PgAgentAdmissionReceipt,
	): Promise<PgEnqueueResult> {
		const existing = await tx
			.select()
			.from(mailbox)
			.where(
				and(
					eq(mailbox.narratorId, input.narratorId),
					eq(mailbox.dedupeKey, mailboxDedupeKey(input)),
				),
			);
		if (existing[0]) return { status: "duplicate", delivery: existing[0] };
		const sources = await tx
			.select({
				id: narratorToolCalls.id,
				narratorId: narratorToolCalls.narratorId,
				attempt: narratorToolCalls.executionAttempt,
				toolUseId: narratorToolCalls.toolUseId,
				identityVersion: narratorToolCalls.executionIdentityVersion,
				originToolCallId: narratorToolCalls.executionOriginToolCallId,
			})
			.from(narratorToolCalls)
			.where(eq(narratorToolCalls.id, receipt.toolCallId));
		const source = sources[0];
		if (
			!source ||
			source.narratorId !== receipt.narratorId ||
			source.attempt !== receipt.attempt ||
			source.toolUseId !== receipt.toolUseId ||
			source.identityVersion !== 1 ||
			source.originToolCallId !== null
		)
			throw new Error("Agent message execution receipt is stale or missing");
		return enqueueSection(tx, input);
	}

	/**
	 * User-buffer admission with placement ordering: the pending-row scan, the seq
	 * assignment (front = below the current minimum, with 0 anchored; back = above the
	 * narrator's inbox counter and every pending row), the insert and the optional FIFO
	 * rewrite of the priority group all commit in ONE section — never a
	 * read-modify-write split across transactions.
	 */
	async function admitUserBufferedSection(
		tx: PgRuntimeTx,
		input: MailboxInput & { kind: "user_input" },
		ordering: PgBufferedOrdering,
	): Promise<PgEnqueueResult> {
		await tx
			.select({ id: narrators.id })
			.from(narrators)
			.where(eq(narrators.id, input.narratorId))
			.for("update");
		const rows = await tx
			.select({ id: mailbox.id, seq: mailbox.seq, priority: mailbox.priority })
			.from(mailbox)
			.where(
				and(
					eq(mailbox.narratorId, input.narratorId),
					eq(mailbox.kind, "user_input"),
					inArray(mailbox.state, ["queued", "failed"]),
				),
			)
			.limit(L.userPending);
		rows.sort((a, b) => a.seq - b.seq);
		const recipient = await tx
			.select({ sequence: narrators.inboxSequence })
			.from(narrators)
			.where(eq(narrators.id, input.narratorId));
		const fifoPriority = ordering.position === "front" && ordering.frontOrder === "fifo";
		const seq =
			ordering.position === "front"
				? Math.min(0, ...rows.map((row) => row.seq)) - 1
				: Math.max(recipient[0]?.sequence ?? 0, ...rows.map((row) => row.seq)) + 1;
		const accepted = await enqueueSection(tx, {
			...input,
			priority: ordering.position === "front",
			seq,
		});
		if (accepted.status === "accepted" && fifoPriority) {
			// Subagent priority inputs historically preserve FIFO within the priority
			// group. Publish their order atomically with acceptance, never afterward.
			const orderedIds = [
				...rows.filter((row) => row.priority).map((row) => row.id),
				accepted.delivery.id,
			];
			const priorityBase = Math.min(0, ...rows.map((row) => row.seq)) - orderedIds.length;
			for (const [order, id] of orderedIds.entries()) {
				await tx
					.update(mailbox)
					.set({ seq: priorityBase + order })
					.where(
						and(
							eq(mailbox.id, id),
							eq(mailbox.narratorId, input.narratorId),
							eq(mailbox.kind, "user_input"),
							inArray(mailbox.state, ["queued", "failed"]),
						),
					);
			}
		}
		return accepted;
	}

	/**
	 * Delivery-consumption acknowledgement: every guard and every write of
	 * `persistAgentMessageConsumption` — the mailbox ack (original or current
	 * revision), the recipient ref's consumption timestamp and the sender's
	 * message-version invalidation — in ONE section. Broadcast-relevant facts are
	 * collected here and returned; the caller broadcasts after COMMIT.
	 */
	async function recordDeliveryConsumptionSection(
		tx: PgRuntimeTx,
		input: PgDeliveryConsumptionInput,
		consumedAt: string,
	): Promise<PgDeliveryConsumptionResult> {
		const row = await getByDelivery(input.deliveryId, tx);
		if (!row) return { status: "missing" };
		if (input.currentRevisionOnly) {
			if (
				row.narratorId !== input.recipientNarratorId ||
				!row.recipientRefId ||
				row.recipientRefId !== input.recipientRefId ||
				input.revision == null ||
				row.currentRevision !== input.revision ||
				row.receiptDisposition === "recipient_deleted" ||
				row.state !== "materialized" ||
				!row.currentMessageId
			)
				return { status: "stale" };
			const ok = await ackCurrentRevisionSection(
				tx,
				input.deliveryId,
				input.recipientNarratorId,
				row.recipientRefId,
				row.currentRevision,
				consumedAt,
			);
			return ok
				? {
						status: "recorded",
						recipientMessageId: row.currentMessageId ?? undefined,
						recipientRefId: row.recipientRefId ?? undefined,
						revision: row.currentRevision,
					}
				: { status: "stale" };
		}
		// The common first-acceptance guards, verbatim from the SQLite consumer.
		if (
			row.narratorId !== input.recipientNarratorId ||
			row.receiptDisposition !== "active" ||
			!row.recipientRefId ||
			!row.currentMessageId ||
			(input.revision != null && row.contentRevision !== input.revision) ||
			(input.recipientRefId != null && row.recipientRefId !== input.recipientRefId) ||
			(!input.mailboxOnly &&
				row.sourceNarratorId != null &&
				row.sourceNarratorId !== input.senderNarratorId) ||
			(input.senderToolCallId != null &&
				(row.sourceToolCallId !== input.senderToolCallId ||
					row.sourceAttempt !== input.sourceAttempt))
		)
			return { status: "stale" };
		const acked = await ackAdoptedSection(
			tx,
			input.deliveryId,
			input.recipientNarratorId,
			row.recipientRefId,
			row.contentRevision,
			consumedAt,
		);
		if (!acked) return { status: "stale" };
		if (input.mailboxOnly && row.kind !== "agent_message")
			return {
				status: "recorded",
				recipientMessageId: row.currentMessageId ?? undefined,
				recipientRefId: row.recipientRefId ?? undefined,
				revision: row.contentRevision,
			};
		// A lost WS frame is repaired by incremental reconnect: bump the sender's
		// (and its parent's, for subagent senders) message version in the SAME
		// transaction as the ack. Broadcast happens post-commit in the caller.
		const senderId = row.sourceNarratorId ?? (input.senderNarratorId || undefined);
		let senderToolUseId: string | undefined;
		if (senderId) {
			const senders = await tx
				.select({ type: narrators.type, parentNarratorId: narrators.parentNarratorId })
				.from(narrators)
				.where(eq(narrators.id, senderId));
			const sender = senders[0];
			const ids = [senderId];
			if (sender?.type === "subagent" && sender.parentNarratorId) ids.push(sender.parentNarratorId);
			await tx
				.update(narrators)
				.set({ messageVersion: sql`${narrators.messageVersion} + 1`, updatedAt: now() })
				.where(inArray(narrators.id, ids));
			const toolCallId = input.senderToolCallId ?? row.sourceToolCallId ?? undefined;
			const attempt = input.sourceAttempt ?? row.sourceAttempt ?? undefined;
			if (toolCallId && attempt != null) {
				const calls = await tx
					.select({ toolUseId: narratorToolCalls.toolUseId })
					.from(narratorToolCalls)
					.where(
						and(
							eq(narratorToolCalls.id, toolCallId),
							eq(narratorToolCalls.executionAttempt, attempt),
						),
					);
				senderToolUseId = calls[0]?.toolUseId ?? undefined;
			}
		}
		return {
			status: "recorded",
			senderId,
			senderToolUseId,
			recipientMessageId: row.currentMessageId ?? undefined,
			recipientRefId: row.recipientRefId ?? undefined,
			revision: row.contentRevision,
		};
	}

	async function claimSection(
		tx: PgRuntimeTx,
		narratorId: string,
		owner: PgClaimOwner,
		accepts: (head: PgEligibleMailboxHead) => boolean,
	): Promise<PgMailboxRow | undefined> {
		if (!(await initializeLegacyMailboxPg(tx, narratorId))) return undefined;
		const head = (await eligibleHeadsPg(tx, narratorId, 1, true))[0];
		if (!head || accepts(head) !== true) return undefined;
		const claimed = await tx
			.update(mailbox)
			.set({
				state: "claimed",
				claimToken: owner.token,
				claimEpoch: owner.epoch,
				claimedAt: now(),
				claimAttempts: sql`${mailbox.claimAttempts} + 1`,
				updatedAt: now(),
			})
			.where(
				and(
					eq(mailbox.id, head.id),
					eq(mailbox.narratorId, narratorId),
					eq(mailbox.state, "queued"),
				),
			)
			.returning();
		return claimed[0];
	}

	async function claimBatchSection(
		tx: PgRuntimeTx,
		narratorId: string,
		owner: PgClaimOwner,
		budget: { count?: number; bytes?: number },
	): Promise<PgMailboxRow[]> {
		if (!(await initializeLegacyMailboxPg(tx, narratorId))) return [];
		const rows = await eligibleHeadsPg(
			tx,
			narratorId,
			Math.min(Math.max(budget.count ?? L.batchCount, 1), L.batchCount),
			true,
		);
		const claimed: PgMailboxRow[] = [];
		let bytes = 0;
		for (const candidate of rows) {
			// User input carries principal/command/attachment barriers; it always gets its own pass.
			if (
				claimed.length &&
				(candidate.kind === "user_input" ||
					claimed[0]?.kind === "user_input" ||
					bytes + candidate.projectedByteSize >
						Math.min(budget.bytes ?? L.batchBytes, L.batchBytes))
			)
				break;
			const updated = await tx
				.update(mailbox)
				.set({
					state: "claimed",
					claimToken: owner.token,
					claimEpoch: owner.epoch,
					claimedAt: now(),
					claimAttempts: sql`${mailbox.claimAttempts} + 1`,
					updatedAt: now(),
				})
				.where(and(eq(mailbox.id, candidate.id), eq(mailbox.state, "queued")))
				.returning();
			const row = updated[0];
			if (row) {
				claimed.push(row);
				bytes += row.projectedByteSize;
			}
			if (bytes >= Math.min(budget.bytes ?? L.batchBytes, L.batchBytes)) break;
		}
		return claimed;
	}

	/** One lock order for Await/commit/transfer/materialize: recipient BEFORE outbox/mailbox.
	 * Held until transaction commit, including an async materializer's history writes. */
	async function lockPublicationRecipient(tx: PgRuntimeTx, recipientId: string): Promise<boolean> {
		// Bound lock waits; withPgRetry replays the whole atomic section on 55P03.
		await tx.execute(sql`SET LOCAL lock_timeout = '2000ms'`);
		const rows = await tx
			.select({ id: narrators.id })
			.from(narrators)
			.where(eq(narrators.id, recipientId))
			.for("update");
		return !!rows[0];
	}
	async function isAwaitedTerminal(tx: PgRuntimeTx, run: PublicationRun): Promise<boolean> {
		const rows = await tx
			.select({ taskId: consumptions.taskId })
			.from(consumptions)
			.where(
				and(
					eq(consumptions.producerKind, run.producerKind),
					eq(consumptions.taskId, run.taskId),
					eq(consumptions.logicalRunId, run.logicalRunId),
					eq(consumptions.recipientId, run.recipientId),
				),
			)
			.limit(1);
		return !!rows[0];
	}
	async function consumeAwaitedTerminalSection(
		tx: PgRuntimeTx,
		run: PublicationRun,
		options: AwaitedTerminalConsumeOptions = {},
	): Promise<void> {
		assertPgRun(run);
		if (!(await lockPublicationRecipient(tx, run.recipientId))) return;
		const sourceResultRef = agentSourceResultRef(options.sourceResultRef);
		if (options.sourceResultRef !== undefined && !sourceResultRef)
			throw new Error("Invalid awaited result source reference");
		await tx
			.insert(consumptions)
			.values({ ...run, consumedAt: now(), sourceResultRef: sourceResultRef ?? null })
			.onConflictDoUpdate({
				target: [
					consumptions.producerKind,
					consumptions.taskId,
					consumptions.logicalRunId,
					consumptions.recipientId,
				],
				set: {
					sourceResultRef: sql`COALESCE(${consumptions.sourceResultRef}, ${sourceResultRef ?? null})`,
				},
			});
		await tx
			.delete(outbox)
			.where(
				and(
					runWhere(run),
					inArray(outbox.eventKind, ["terminal", "completed", "failed", "timed_out", "cancelled"]),
				),
			);
		const keys = (["completed", "failed", "timed_out", "cancelled"] as const).map((event) =>
			publicationDedupeKey(run, event),
		);
		await tx
			.update(mailbox)
			.set({
				state: "cancelled",
				...releasedPayload,
				claimToken: null,
				claimEpoch: null,
				claimedAt: null,
				lastError: AWAITED_TERMINAL_CONSUMED_REASON,
				updatedAt: now(),
			})
			.where(
				and(
					eq(mailbox.narratorId, run.recipientId),
					eq(mailbox.kind, "task_notice"),
					eq(mailbox.noticeKind, run.producerKind),
					inArray(mailbox.dedupeKey, keys),
					inArray(mailbox.state, ["queued", "claimed", "failed"]),
					isNull(mailbox.recipientRefId),
					isNull(mailbox.currentMessageId),
				),
			);
	}
	async function materializeSection(
		tx: PgRuntimeTx,
		claim: MailboxClaim,
		materializer: PgMaterializer,
	): Promise<PgMailboxRow> {
		const dependencies = (await materializer.planNarratorLocks?.(tx, claim)) ?? [];
		if (dependencies.length > L.pageSize)
			throw new Error("Materializer narrator lock budget exceeded");
		const narratorIds = [...new Set([claim.narratorId, ...dependencies])].sort();
		await tx.execute(sql`SET LOCAL lock_timeout = '2000ms'`);
		await lockPgNarratorRefs(tx, narratorIds);
		restrictPgNarratorLocks(tx, narratorIds);
		// Revalidate state/token/epoch under the claim row lock, AFTER all narrator locks.
		const row = await requireClaim(tx, claim);
		const binding = await materializer(tx, row);
		if (binding.messageId !== row.recipientMessageId)
			throw new Error("Materializer must use reserved message identity");
		const refs = await tx
			.select({ id: narratorMessageRefs.id })
			.from(narratorMessageRefs)
			.where(
				and(
					eq(narratorMessageRefs.id, binding.refId),
					eq(narratorMessageRefs.narratorId, row.narratorId),
					eq(narratorMessageRefs.messageId, binding.messageId),
				),
			);
		if (!refs[0])
			throw new Error("Materializer did not persist the recipient ref in this transaction");
		const updated = await tx
			.update(mailbox)
			.set({
				state: "materialized",
				recipientRefId: refs[0].id,
				currentMessageId: binding.messageId,
				contentRevision: binding.revision ?? row.contentRevision,
				currentRevision: binding.revision ?? row.contentRevision,
				...releasedPayload,
				claimToken: null,
				claimEpoch: null,
				claimedAt: null,
				lastError: null,
				updatedAt: now(),
			})
			.where(claimWhere(claim))
			.returning();
		const result = updated[0];
		if (!result) throw new Error("Stale mailbox claim");
		return result;
	}

	async function ackCurrentRevisionSection(
		tx: PgRuntimeTx,
		deliveryId: string,
		narratorId: string,
		refId: string,
		revision: number,
		at: string,
	): Promise<boolean> {
		const row = await getByDelivery(deliveryId, tx);
		if (
			!row ||
			row.narratorId !== narratorId ||
			row.recipientRefId !== refId ||
			row.currentRevision !== revision ||
			row.receiptDisposition === "recipient_deleted" ||
			row.state !== "materialized" ||
			!row.currentMessageId
		)
			return false;
		const refWhere = and(
			eq(narratorMessageRefs.id, refId),
			eq(narratorMessageRefs.narratorId, narratorId),
			eq(narratorMessageRefs.messageId, row.currentMessageId),
		);
		const refs = await tx
			.select({
				id: narratorMessageRefs.id,
				adoptedAtMs: narratorMessageRefs.injectionConsumedAt,
			})
			.from(narratorMessageRefs)
			.where(refWhere);
		const ref = refs[0];
		if (!ref) return false;
		// PG stores injection_consumed_at as bigint epoch-ms (the SQLite build reads a
		// Date from its timestamp_ms column); the ISO string below is the mailbox's
		// text-clock representation of the same instant.
		if (ref.adoptedAtMs == null)
			await tx
				.update(narratorMessageRefs)
				.set({ injectionConsumedAt: Date.parse(at) })
				.where(refWhere);
		const adoptedAtIso =
			row.currentAdoptedAt ??
			(ref.adoptedAtMs != null ? new Date(ref.adoptedAtMs).toISOString() : null) ??
			at;
		const updated = await tx
			.update(mailbox)
			.set({
				currentAdoptedRevision: revision,
				currentAdoptedAt: adoptedAtIso,
				updatedAt: now(),
			})
			.where(
				and(
					eq(mailbox.id, row.id),
					eq(mailbox.currentRevision, revision),
					eq(mailbox.currentMessageId, row.currentMessageId),
					eq(mailbox.receiptDisposition, row.receiptDisposition),
				),
			)
			.returning({ id: mailbox.id });
		return updated.length === 1;
	}

	async function ackAdoptedSection(
		tx: PgRuntimeTx,
		deliveryId: string,
		narratorId: string,
		refId: string,
		revision: number,
		at: string,
	): Promise<boolean> {
		const row = await getByDelivery(deliveryId, tx);
		if (
			!row ||
			row.narratorId !== narratorId ||
			row.recipientRefId !== refId ||
			row.contentRevision !== revision ||
			row.receiptDisposition !== "active" ||
			row.state !== "materialized"
		)
			return false;
		const refWhere = and(
			eq(narratorMessageRefs.id, refId),
			eq(narratorMessageRefs.narratorId, narratorId),
			eq(narratorMessageRefs.messageId, row.currentMessageId ?? ""),
		);
		const consumed = await tx
			.update(narratorMessageRefs)
			.set({ injectionConsumedAt: Date.parse(at) })
			.where(and(refWhere, isNull(narratorMessageRefs.injectionConsumedAt)))
			.returning({ id: narratorMessageRefs.id });
		if (!consumed.length) {
			const existing = await tx
				.select({ id: narratorMessageRefs.id })
				.from(narratorMessageRefs)
				.where(refWhere);
			if (!existing[0]) return false;
		}
		await tx
			.update(mailbox)
			.set({
				adoptedRevision: revision,
				adoptedAt: row.adoptedAt ?? at,
				currentRevision: revision,
				currentAdoptedRevision: revision,
				currentAdoptedAt: row.currentAdoptedAt ?? row.adoptedAt ?? at,
				updatedAt: now(),
			})
			.where(eq(mailbox.id, row.id));
		return true;
	}

