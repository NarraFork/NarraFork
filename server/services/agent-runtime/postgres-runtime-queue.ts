/**
 * Deliberate mirror of the SQLite store's payload validator (`mailbox.ts` `validate`,
 * which is module-private there). Extraction into a shared engine-neutral module is a
 * cross-track change this adapter deliberately does not make; the copies must agree,
 * and the real-PostgreSQL suite exercises the same rejections through this one.
 */
function validatePgInput(input: MailboxInput) {
	pointer(input.narratorId);
	const inlineBytes = Buffer.byteLength(input.text);
	const byteSize = input.payloadRef?.byteSize ?? inlineBytes;
	if (
		!Number.isSafeInteger(byteSize) ||
		byteSize < inlineBytes ||
		!Number.isSafeInteger(input.projectedByteSize) ||
		input.projectedByteSize < byteSize
	)
		throw new Error("Invalid payload/projection size");
	if (inlineBytes > L.inlineBytes)
		throw new Error("Large user payload requires a managed file reference");
	if (input.payloadRef) {
		pointer(input.payloadRef.path);
		if (input.kind !== "user_input")
			throw new Error("Only user inputs may use large body references");
	}
	if (
		input.kind === "agent_message" &&
		(byteSize > L.agentBodyBytes || input.projectedByteSize > L.agentProjectedBytes)
	)
		throw new Error("Send exceeds body/projection limit; use a file reference or summary");
	const metadataJson = input.metadata
		? boundedJson(
				input.metadata,
				input.kind === "task_notice" ? L.publicationBytes : L.metadataBytes,
			)
		: null;
	const payloadRefJson = input.payloadRef ? boundedJson(input.payloadRef, L.metadataBytes) : null;
	if (
		input.kind === "task_notice" &&
		inlineBytes + Buffer.byteLength(metadataJson ?? "") > L.publicationBytes
	)
		throw new Error("Task notice must contain only a bounded summary and pointers");
	if (input.kind === "user_input") {
		const refs = [
			input.imagesJson,
			input.creatorJson,
			input.textFilePathsJson,
			input.fileReferencesJson,
			input.commandText,
			input.bashCommand,
		];
		if (
			refs.reduce((n, value) => n + Buffer.byteLength(value ?? ""), 0) +
				Buffer.byteLength(metadataJson ?? "") +
				Buffer.byteLength(payloadRefJson ?? "") >
			L.metadataBytes
		)
			throw new Error("Attachment metadata exceeds mailbox budget; use bounded references");
	}
	return { byteSize, metadataJson, payloadRefJson };
}

function assertPgRun(run: PublicationRun) {
	if (run.producerKind !== "agent" && run.producerKind !== "bash")
		throw new Error("Invalid publication producer identity");
	for (const p of [run.taskId, run.logicalRunId, run.recipientId])
		if (typeof p !== "string" || !p || Buffer.byteLength(p) > 256)
			throw new Error("Invalid publication pointer");
}

function claimWhere(claim: MailboxClaim) {
	return and(
		eq(mailbox.id, claim.id),
		eq(mailbox.narratorId, claim.narratorId),
		eq(mailbox.state, "claimed"),
		eq(mailbox.claimToken, claim.token),
		eq(mailbox.claimEpoch, claim.epoch),
	);
}

async function requireClaim(tx: PgRuntimeTx, claim: MailboxClaim): Promise<PgMailboxRow> {
	const rows = await tx.select().from(mailbox).where(claimWhere(claim)).for("update");
	const row = rows[0];
	if (!row) throw new Error("Stale mailbox claim");
	return row;
}

/**
 * The arrival-sequence counter claim — `UPDATE narrators SET inbox_sequence =
 * inbox_sequence + 1 … RETURNING`. The narrators row lock serializes concurrent
 * claimants, so two connections can never observe the same value, and a rolled-back
 * claim is re-issued because the bump rolls back with the transaction. Verified under
 * real concurrency in the sibling shape suite; re-verified here through the adapter.
 */
async function allocateArrivalSequencePg(tx: PgRuntimeTx, narratorId: string): Promise<number> {
	const rows = await tx
		.update(narrators)
		.set({ inboxSequence: sql`${narrators.inboxSequence} + 1` })
		.where(eq(narrators.id, narratorId))
		.returning({ seq: narrators.inboxSequence });
	const row = rows[0];
	if (!row) throw new Error("Mailbox recipient does not exist");
	return row.seq;
}

async function mailboxHasCapacityPg(
	tx: PgRuntimeTx,
	narratorId: string,
	kind: PgMailboxRow["kind"],
	noticeKind?: NoticeKind,
): Promise<boolean> {
	const cap =
		kind === "user_input"
			? L.userPending
			: kind === "agent_message"
				? L.agentPending
				: L.noticePending;
	const rows = await tx
		.select({ id: mailbox.id })
		.from(mailbox)
		.where(
			and(
				eq(mailbox.narratorId, narratorId),
				eq(mailbox.kind, kind),
				kind === "task_notice" ? eq(mailbox.noticeKind, noticeKind as NoticeKind) : undefined,
				inArray(mailbox.state, pendingStates),
			),
		)
		.limit(cap);
	return rows.length < cap;
}

/** One bounded backfill page per call, same contract as the SQLite store. */
async function initializeLegacyMailboxPg(tx: PgRuntimeTx, narratorId: string): Promise<boolean> {
	const rows = await tx
		.select({ id: mailbox.id })
		.from(mailbox)
		.where(and(eq(mailbox.narratorId, narratorId), isNull(mailbox.arrivalSeq)))
		.orderBy(asc(mailbox.seq), asc(mailbox.id))
		.limit(L.pageSize + 1);
	for (const row of rows.slice(0, L.pageSize)) {
		const arrivalSeq = await allocateArrivalSequencePg(tx, narratorId);
		await tx
			.update(mailbox)
			.set({
				arrivalSeq,
				deliveryId: generateId(),
				recipientMessageId: generateId(),
				updatedAt: now(),
			})
			.where(and(eq(mailbox.id, row.id), isNull(mailbox.arrivalSeq)));
	}
	return rows.length <= L.pageSize;
}

/**
 * The publication-aware eligible head. The barrier is read first (its own statement),
 * then candidates are locked `FOR UPDATE SKIP LOCKED`: a row claimed by a concurrent
 * consumer is skipped rather than blocked on, which is the claim serialization this
 * adapter is required to provide. PG returns NULLS LAST on ASC for the nullable
 * `arrival_seq`; pending outbox rows always carry one, so the barrier comparison is
 * over the same non-null population the SQLite store sees.
 */
async function eligibleHeadsPg(
	tx: PgRuntimeTx,
	narratorId: string,
	count: number,
	skipLocked: boolean,
): Promise<PgEligibleMailboxHead[]> {
	const barrierRows = await tx
		.select({ arrivalSeq: outbox.arrivalSeq })
		.from(outbox)
		.where(and(eq(outbox.recipientId, narratorId), eq(outbox.state, "pending")))
		.orderBy(asc(outbox.arrivalSeq))
		.limit(1);
	const barrier = barrierRows[0]?.arrivalSeq;
	const query = tx
		.select({
			id: mailbox.id,
			narratorId: mailbox.narratorId,
			kind: mailbox.kind,
			metadataJson: mailbox.metadataJson,
			projectedByteSize: mailbox.projectedByteSize,
			arrivalSeq: mailbox.arrivalSeq,
			seq: mailbox.seq,
			priority: mailbox.priority,
			createdBy: mailbox.createdBy,
			deliveryId: mailbox.deliveryId,
		})
		.from(mailbox)
		.where(
			and(
				eq(mailbox.narratorId, narratorId),
				eq(mailbox.state, "queued"),
				barrier == null ? undefined : lt(mailbox.arrivalSeq, barrier),
			),
		)
		.orderBy(
			desc(mailbox.priority),
			sql`CASE WHEN ${mailbox.kind} = 'user_input' THEN ${mailbox.seq} ELSE ${mailbox.arrivalSeq} END`,
			asc(mailbox.arrivalSeq),
		)
		.limit(count);
	return skipLocked ? await query.for("update", { skipLocked: true }) : await query;
}

