/**
 * Fail-closed verdict for the schema-dependent legacy surface. Raised by the
 * legacy-admission operations when the store cannot prove the insertion-ordinal
 * clock exists and has been captured. The error names the exact pending item so a
 * caller can never mistake "not yet wired" for "nothing to do".
 */
export class RuntimeQueueSchemaPendingError extends Error {
	/** Exact pending schema items, e.g. "narrators.insert_seq". Empty once the schema probe passed. */
	readonly pendingSchema: readonly string[];
	/**
	 * "schema"     — the live catalog probe found insert_seq columns missing.
	 * "activation" — the columns may exist, but this store has not run its bounded
	 *                activation (probe + boundary capture) yet.
	 */
	readonly reason: "schema" | "activation";
	constructor(
		operation: string,
		pendingSchema: readonly string[],
		reason: "schema" | "activation",
	) {
		super(
			reason === "schema"
				? `PostgreSQL runtime queue operation "${operation}" is blocked on schema: ` +
						`${pendingSchema.join(", ")}. The insert_seq identity columns are absent from ` +
						"the live catalog; this adapter fails closed instead of substituting an " +
						"approximate insertion clock, and never falls back to SQLite."
				: `PostgreSQL runtime queue operation "${operation}" is blocked: legacy admission ` +
						"has not been activated on this store. Call activateLegacyAdmission() once " +
						"from a bounded startup/initialization path; the boundary is never captured " +
						"per-operation, and there is no SQLite fallback.",
		);
		this.name = "RuntimeQueueSchemaPendingError";
		this.pendingSchema = pendingSchema;
		this.reason = reason;
	}
}

/** The three tables whose `insert_seq` identity columns the legacy boundary needs. */
const INSERT_SEQ_TABLES = ["background_tasks", "narrators", "narrator_tool_continuations"] as const;

export interface RuntimeQueueSchemaReadiness {
	/**
	 * "unknown" until {@link probeRuntimeQueueSchema} or activation has read the live
	 * catalog; "available" only when ALL three insert_seq columns are present. A store
	 * that has never probed must not claim either verdict.
	 */
	readonly insertSeqOrdinal: "unknown" | "available" | "missing";
	/** The pending items, e.g. ["background_tasks.insert_seq"]. Empty when available. */
	readonly pendingSchema: readonly string[];
	/**
	 * "available" only after activation actually succeeded against the live database:
	 * schema probe passed AND the boundary capture ran. Anything else is "blocked".
	 */
	readonly legacyAdmission: "blocked" | "available";
}

/** The verdict a freshly constructed store may honestly report: nothing verified yet. */
function unprobedReadiness(): RuntimeQueueSchemaReadiness {
	return {
		insertSeqOrdinal: "unknown",
		pendingSchema: INSERT_SEQ_TABLES.map((table) => `${table}.insert_seq`),
		legacyAdmission: "blocked",
	};
}

/**
 * Read the live schema verdict: which of the three `insert_seq` identity columns
 * exist. Structural executor shape (`PgExecutor` from `pg-fts.ts` satisfies it), so
 * the composition root can run this probe on the runtime executor and tests can run
 * it on any handle — no drizzle, no store construction.
 */
export async function probeRuntimeQueueSchema(executor: {
	unsafe: (query: string, params?: unknown[]) => Promise<Record<string, unknown>[]>;
}): Promise<RuntimeQueueSchemaReadiness> {
	const rows = await executor.unsafe(
		`SELECT table_name FROM information_schema.columns
			WHERE table_schema = current_schema() AND column_name = 'insert_seq'
			AND data_type = 'bigint' AND is_nullable = 'NO'
			AND is_identity = 'YES' AND identity_generation = 'BY DEFAULT'
			AND table_name IN ('background_tasks', 'narrators', 'narrator_tool_continuations')`,
	);
	const present = new Set(rows.map((row) => String(row.table_name)));
	const pending = INSERT_SEQ_TABLES.filter((table) => !present.has(table)).map(
		(table) => `${table}.insert_seq`,
	);
	return {
		insertSeqOrdinal: pending.length === 0 ? "available" : "missing",
		pendingSchema: pending,
		// A catalog probe alone never activates legacy admission; only a store that ran
		// its boundary capture may claim that.
		legacyAdmission: "blocked",
	};
}

