/**
 * agent-runtime/postgres-runtime-queue.ts — the PostgreSQL production adapter for the
 * runtime queue (mailbox + publication outbox atomic write sections).
 *
 * WHAT THIS MODULE IS
 * -------------------
 * The genuinely-async sibling of the SQLite queue stores (`mailbox.ts`,
 * `publication-outbox.ts`), composed over a caller-supplied `BunSQLDatabase` handle.
 * Same DOMAIN operations, same guards in the same order, same error vocabulary; every
 * dialect-shaped decision lives here:
 *
 *   - PROMISE boundary: every operation is honestly async against a networked driver.
 *     An `await` between BEGIN and COMMIT is safe here — the exact opposite of the
 *     SQLite seam (`runtime-write.ts`), whose guard exists because it is not.
 *   - RETRY UNIT = WHOLE SECTION: `withPgRetry` (`server/db/pg-retry.ts`) wraps BEGIN
 *     through COMMIT, never a single statement. Retryable SQLSTATEs preserve their
 *     original identity and retry the entire aborted transaction; domain failures
 *     and unknown network/commit outcomes are never blindly replayed. Every section is idempotent under
 *     replay: dedupe/unique indexes are the no-duplicate authority (a replayed
 *     enqueue INSERT collides on `idx_nbm_dedupe` and surfaces as
 *     `WriteConflictError` → re-read → `duplicate`), and claim/ack/fail re-read
 *     state instead of assuming it.
 *   - CLAIM USES `FOR UPDATE SKIP LOCKED`: head selection locks the candidate row(s)
 *     inside the section, so a concurrent claimer SKIPS a locked head instead of
 *     blocking on it and losing to EPQ re-evaluation. The follow-up UPDATE still
 *     carries `state = 'queued'` in its WHERE as the load-bearing guard.
 *   - CONFLICTS CROSS AS VOCABULARY: SQLSTATE classification (`pg-errors.ts`) +
 *     translation (`runtime-write.ts` {@link translateWriteError}, imported — this
 *     module does not modify or wrap the SQLite seam) happen at the operation
 *     boundary, AFTER the retry unit. 23505 is never retried into a false success.
 *   - SIDE EFFECTS AFTER COMMIT: this store performs no broadcasts, wake-ups or cache
 *     writes. An operation resolves only after its section has committed (exactly
 *     once — `withPgRetry` resolves once), so callers run their side effects after
 *     the await, the way `publication.ts` runs `wake` after its SQLite sections
 *     return.
 *
 * LEGACY ADMISSION: REAL ON insert_seq, GATED BY ACTIVATION
 * -----------------------------------------------------------
 * The legacy-admission operations (`registerLegacyRunningRunSlots`,
 * `registerLegacyUnknownBashFailure`, `registerLegacyCompletedRunSlots`) depend on a
 * per-table insertion ordinal. On SQLite that ordinal is the implicit rowid; on
 * PostgreSQL it is the `insert_seq BIGINT GENERATED BY DEFAULT AS IDENTITY` columns
 * on `background_tasks`, `narrators` and `narrator_tool_continuations` (landed in
 * `drizzle-postgres/0001_seq_counters.sql`). This module reads `insert_seq` and
 * nothing else as the ordinal — never timestamps or MAX+1 as an allocation clock,
 * and never a SQLite fallback.
 *
 * Two gates keep the surface honest:
 *
 *   1. ACTIVATION. The boundary maxima (`max(insert_seq)` per table) are captured
 *      ONCE by {@link PostgresRuntimeQueue.activateLegacyAdmission} — a bounded
 *      startup/initialization call (single statement, `SET LOCAL statement_timeout`,
 *      logged), never on a per-operation hot path. Legacy operations called before
 *      activation reject with {@link RuntimeQueueSchemaPendingError}
 *      (`reason: "activation"`). Activation re-probes the live catalog: a column
 *      that is missing leaves the store blocked (`reason: "schema"`) with the exact
 *      pending list, and activation may be retried after the schema lands.
 *   2. THE BOUNDARY COMPARISON. Identity values assigned to existing rows by the
 *      migration do NOT reconstruct historical insertion order. We capture only
 *      AFTER migration and compare with that cutoff. Explicit SQLite ordinal imports
 *      are also supported once the importer advances the sequence past its maximum.
 *      Startup briefly locks the three tables to drain in-flight writers; later
 *      native INSERTs have `insert_seq > capturedTop`, regardless of backdated
 *      timestamps. Application callers must never override/reseed identities.
 *
 * Everything else in this module runs on columns the PostgreSQL schema already
 * carries and needs no activation.
 *
 * WHAT THIS MODULE IS NOT
 * -----------------------
 * Not a wrapper around the SQLite path: nothing here imports `server/db`,
 * `server/db/schema.ts` at runtime, or a SQLite dialect module, and no operation
 * delegates to the SQLite stores. The wiring that re-points the ad-hoc
 * `createMailboxStore(db)` call sites at this adapter belongs to the caller-migration
 * track (P2); this module is the injectable unit that track consumes, and the
 * composition seam (`services/postgres-composition.ts`) is where it enters
 * production. Legacy admission is verified against the complete production journal
 * in `tests/server/services/agent-runtime/pg-runtime-queue-legacy.test.ts`. The core
 * queue's earlier scratch-schema tests remain supplementary, not migration proof.
 */

