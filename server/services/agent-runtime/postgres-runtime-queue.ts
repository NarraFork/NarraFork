/**
 * The captured legacy boundary: at protocol activation, the top `insert_seq` ordinal
 * of each of the three legacy-source tables, plus the wall-clock capture instant for
 * the timestamp cross-checks. `null` tops (empty tables) collapse to 0 — a fresh
 * PostgreSQL deployment has no pre-protocol data to admit at all.
 *
 * Captured ONCE per store by `activateLegacyAdmission`; the hot path only compares
 * against the cached numbers. Existing-row identity assignment is not historical
 * insertion order. Only the cutoff captured after migration has meaning here;
 * explicit ordinal imports require the importer to advance their sequences.
 */
interface PgLegacyBoundary {
	readonly capturedAtMs: number;
	readonly backgroundInsertSeq: number;
	readonly narratorInsertSeq: number;
	readonly checkpointInsertSeq: number;
	readonly completionTokens: WeakMap<object, Readonly<LegacyCompletionAdmission>>;
}

