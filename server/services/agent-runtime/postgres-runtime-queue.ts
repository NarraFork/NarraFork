/**
 * The bound queue store, injected once from `services/postgres-composition.ts`.
 *
 * The binding itself lives in `runtime-queue-port.ts`, the backend-neutral selector
 * module: ONE binding, resolved fail-closed (explicit PostgreSQL with no injected
 * store throws; a read/write backend mismatch throws; SQLite stays the default),
 * never a per-call backend probe. These three accessors keep their original names
 * and semantics as thin delegates so existing call sites and tests are untouched.
 */
export function setPostgresRuntimeQueue(store: PostgresRuntimeQueue | undefined): void {
	bindRuntimeQueue(store ? { backend: "postgres", queue: store } : undefined);
}

/** The injected queue store, or undefined when the process runs on SQLite. */
export function getPostgresRuntimeQueue(): PostgresRuntimeQueue | undefined {
	return getRuntimeQueuePort();
}

/**
 * Fail-closed accessor for the P2 call sites: a process that believes it is on
 * PostgreSQL with no queue store injected is a wiring bug, not a SQLite fallback.
 */
export function requirePostgresRuntimeQueue(): PostgresRuntimeQueue {
	return requireRuntimeQueuePort();
}
