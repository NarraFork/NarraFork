/**
 * Embed the builtin plugin packages into a generated TS module.
 *
 * A compiled single-file binary has no `server/builtin-plugins/` directory: every module
 * reports the executable as `import.meta.url` (see `lib/runtime-target.ts`), and nothing else
 * from the source tree is on disk. The same constraint is why migrations, the frontend bundle,
 * the changelog and the license manifest are all generated into `server/generated/*.ts` — a
 * compiled binary can only rely on what the bundler inlined.
 *
 * The builtin plugin cannot simply be imported as code: the plugin runtime reads the package
 * from a directory (manifest.json, then the `server.entry` file, both through the ordinary
 * package reader's size/JSON/schema/entry/escape checks). So the files are embedded here as
 * text and materialized back onto disk at startup — see `builtin-plugins/materialize.ts`.
 *
 * Text only, deliberately: no binary assets are permitted in a plugin package, and `utf8`
 * round-trips the JSON and JS the packages contain.
 */
import { mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

/**
 * The package directories to embed, scanned directly rather than imported from
 * `server/builtin-plugins/registry.ts`: that module reaches materialize.ts, which imports the
 * file this script generates — importing it here would be a chicken-and-egg cycle on a clean
 * tree. The list is deliberately the same one, and a test asserts they agree.
 */
const NON_PACKAGE_ENTRIES = new Set(["registry.ts", "materialize.ts"]);

const OUTPUT = join(import.meta.dir, "..", "server", "generated", "embedded-builtin-plugins.ts");

/** Every file of one package, keyed by its POSIX path inside the package. */
interface EmbeddedFile {
	path: string;
	content: string;
}

interface EmbeddedPackage {
	/** Directory name under `BUILTIN_PLUGIN_ROOTS`, e.g. "apikey-quota". */
	dir: string;
	pluginId: string;
	version: string;
	files: EmbeddedFile[];
}

async function listFiles(root: string, dir = root): Promise<string[]> {
	const out: string[] = [];
	for (const entry of await readdir(dir, { withFileTypes: true })) {
		const full = join(dir, entry.name);
		if (entry.isDirectory()) out.push(...(await listFiles(root, full)));
		else if (entry.isFile()) out.push(full);
	}
	return out;
}

async function readPackage(root: string): Promise<EmbeddedPackage> {
	const manifestRaw = await readFile(join(root, "manifest.json"), "utf8");
	const manifest = JSON.parse(manifestRaw) as { pluginId?: unknown; version?: unknown };
	if (typeof manifest.pluginId !== "string" || typeof manifest.version !== "string") {
		throw new Error(`${root}: manifest.json is missing pluginId/version`);
	}
	const files: EmbeddedFile[] = [];
	for (const file of await listFiles(root)) {
		const bytes = await stat(file);
		if (bytes.size > 4 * 1024 * 1024) {
			throw new Error(`${relative(root, file)}: refusing to embed a file above 4 MiB`);
		}
		files.push({
			path: relative(root, file).split(sep).join("/"),
			content: await readFile(file, "utf8"),
		});
	}
	files.sort((a, b) => a.path.localeCompare(b.path));
	return {
		dir: root.split(/[\\/]/).pop() ?? root,
		pluginId: manifest.pluginId,
		version: manifest.version,
		files,
	};
}

export async function renderBuiltinPluginModule(
	root = join(import.meta.dir, ".."),
): Promise<string> {
	const packages: EmbeddedPackage[] = [];
	const builtinRoot = join(root, "server", "builtin-plugins");
	for (const entry of await readdir(builtinRoot, { withFileTypes: true })) {
		if (!entry.isDirectory()) continue;
		if (NON_PACKAGE_ENTRIES.has(entry.name)) continue;
		packages.push(await readPackage(join(builtinRoot, entry.name)));
	}

	return `// GENERATED by scripts/generate-builtin-plugins.ts — do not edit.
// Builtin packages are shared by release and immutable local runtime builds.
export interface EmbeddedBuiltinFile {
	path: string;
	content: string;
}
export interface EmbeddedBuiltinPackage {
	dir: string;
	pluginId: string;
	version: string;
	files: readonly EmbeddedBuiltinFile[];
}
export const embeddedBuiltinPlugins: readonly EmbeddedBuiltinPackage[] = ${JSON.stringify(packages, null, "\t")} as const;
`;
}

if (import.meta.main) {
	const body = await renderBuiltinPluginModule();
	await mkdir(join(import.meta.dir, "..", "server", "generated"), { recursive: true });
	await writeFile(OUTPUT, body, "utf8");
	console.log(`Generated ${relative(process.cwd(), OUTPUT)}`);
}
