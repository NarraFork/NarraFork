/**
 * build-local-exe.mjs — local Windows exe build (BUILD.md flow).
 *
 * Bypasses scripts/build-cross-platform.ts, which references modules missing
 * upstream (scripts/lib/binary-metadata.ts, scripts/post-process-worker.ts).
 * Implements the same core steps: embed frontend + migrations, then compile
 * with the official flags (multi-entry incl. db worker, --minify,
 * --asset-naming, --external=electron). Publishing post-processing
 * (signing/zstd/latest.yml/checksums) is skipped — not needed for local use.
 *
 * Run: bun build-local-exe.mjs
 */

import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = import.meta.dir;
const FRONTEND_DIR = join(ROOT, "dist", "frontend");
const DRIZZLE_DIR = join(ROOT, "drizzle");
const GENERATED_DIR = join(ROOT, "server", "generated");
const VERSION = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf-8")).version ?? "0.0.0";
// BUILD_SUFFIX lets you avoid clobbering a currently running exe (Windows
// cannot overwrite a live binary): e.g. BUILD_SUFFIX=fix32 bun build-local-exe.mjs
const SUFFIX = process.env.BUILD_SUFFIX ?? "fix31";
const OUT = join(ROOT, "dist", `narrafork-${VERSION}-windows-x64-${SUFFIX}.exe`);

function walkDir(dir) {
	const out = [];
	for (const name of readdirSync(dir)) {
		const p = join(dir, name);
		if (statSync(p).isDirectory()) out.push(...walkDir(p));
		else out.push(p);
	}
	return out;
}

// ---- Step 1: embedded-frontend.ts -----------------------------------------
if (!existsSync(join(FRONTEND_DIR, "index.html"))) {
	console.error("dist/frontend missing — run `bun run build` first");
	process.exit(1);
}
const files = walkDir(FRONTEND_DIR);
const imports = [];
const mapEntries = [];
for (let i = 0; i < files.length; i++) {
	const rel = relative(ROOT, files[i]);
	const urlPath = `/${relative("dist/frontend", rel).replaceAll("\\", "/")}`;
	const importPath = `../../${rel.replaceAll("\\", "/")}`;
	imports.push(`import _f${i} from ${JSON.stringify(importPath)} with { type: "file" };`);
	mapEntries.push(`\t${JSON.stringify(urlPath)}: _f${i},`);
}
mkdirSync(GENERATED_DIR, { recursive: true });
writeFileSync(
	join(GENERATED_DIR, "embedded-frontend.ts"),
	`// AUTO-GENERATED by build-local-exe.mjs — DO NOT EDIT\n${imports.join("\n")}\n\n/** URL path → embedded file path (resolved at compile time via $bunfs) */\nexport const embeddedAssets: Record<string, string> = {\n${mapEntries.join("\n")}\n};\n`,
);
console.log(`✓ embedded-frontend.ts (${files.length} files)`);

// ---- Step 2: embedded-migrations-data.ts ----------------------------------
const journalPath = join(DRIZZLE_DIR, "meta", "_journal.json");
if (!existsSync(journalPath)) {
	console.error("drizzle journal missing — run `bun run db:generate` first");
	process.exit(1);
}
const journalJson = readFileSync(journalPath, "utf-8");
const journal = JSON.parse(journalJson);
const sqlEntries = journal.entries
	.map((entry) => {
		const fileName = `${entry.tag}.sql`;
		const filePath = join(DRIZZLE_DIR, fileName);
		if (!existsSync(filePath)) {
			console.error(`missing migration SQL: ${fileName}`);
			process.exit(1);
		}
		return `\t{ name: ${JSON.stringify(fileName)}, content: ${JSON.stringify(readFileSync(filePath, "utf-8"))} },`;
	})
	.join("\n");
writeFileSync(
	join(GENERATED_DIR, "embedded-migrations-data.ts"),
	`// AUTO-GENERATED by build-local-exe.mjs — DO NOT EDIT\nexport const embeddedMigrationJournalJson = ${JSON.stringify(journalJson)};\nexport const embeddedMigrationSqlFiles = [\n${sqlEntries}\n];\n`,
);
console.log(`✓ embedded-migrations-data.ts (${journal.entries.length} migrations)`);

// ---- Step 3: build-info.ts ------------------------------------------------
const commit = execSync("git rev-parse --short HEAD", { cwd: ROOT }).toString().trim();
writeFileSync(
	join(GENERATED_DIR, "build-info.ts"),
	`// AUTO-GENERATED by build-local-exe.mjs — DO NOT EDIT\nexport const buildVersion = ${JSON.stringify(VERSION)};\nexport const buildCommit = ${JSON.stringify(commit)};\nexport const buildPlatform = "win-x64";\n`,
);
console.log(`✓ build-info.ts (${VERSION} @ ${commit})`);

// ---- Step 4: compile (official flags) --------------------------------------
console.log(`Compiling -> ${OUT}`);
const compile = Bun.spawnSync(
	[
		"bun",
		"build",
		"./server/index.ts",
		"./server/lib/db-worker/worker-entry.ts",
		"--compile",
		"--minify",
		"--target=bun-windows-x64",
		"--asset-naming=[dir]/[name].[ext]",
		"--external=electron",
		"--outfile",
		OUT,
	],
	{ cwd: ROOT, stdio: ["inherit", "inherit", "inherit"] },
);
if (compile.exitCode !== 0) {
	console.error("Compilation failed");
	process.exit(compile.exitCode ?? 1);
}
console.log(`✓ ${OUT}`);
